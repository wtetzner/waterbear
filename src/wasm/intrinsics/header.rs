//! Language bindings generated from the intrinsic registry.

use std::fmt::Write;

use clap::ValueEnum;

use super::{AbiType, IntrinsicDefinition, IntrinsicParameter, definitions};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, ValueEnum)]
pub enum HeaderLanguage {
    #[default]
    C,
    #[value(alias = "c++", alias = "cxx")]
    Cpp,
    Rust,
}

pub fn render(language: HeaderLanguage) -> String {
    let definitions = definitions();
    match language {
        HeaderLanguage::C => render_c(&definitions),
        HeaderLanguage::Cpp => render_cpp(&definitions),
        HeaderLanguage::Rust => render_rust(&definitions),
    }
}

fn render_c(definitions: &[IntrinsicDefinition]) -> String {
    let mut output = String::new();
    writeln!(output, "/* Generated by `waterbear wasm header`. */").unwrap();
    writeln!(output, "#ifndef WATERBEAR_VMU_INTRINSICS_H").unwrap();
    writeln!(output, "#define WATERBEAR_VMU_INTRINSICS_H").unwrap();
    writeln!(output).unwrap();
    writeln!(output, "#include <stdint.h>").unwrap();
    writeln!(output).unwrap();
    write_c_declarations(&mut output, definitions, CFamily::C);
    writeln!(output, "#endif").unwrap();
    output
}

fn render_cpp(definitions: &[IntrinsicDefinition]) -> String {
    let mut output = String::new();
    writeln!(output, "// Generated by `waterbear wasm header`.").unwrap();
    writeln!(output, "#pragma once").unwrap();
    writeln!(output).unwrap();
    // Clang provides the C compatibility header for freestanding WASM targets;
    // the hosted C++ standard library is intentionally not required.
    writeln!(output, "#include <stdint.h>").unwrap();
    writeln!(output).unwrap();
    writeln!(output, "extern \"C\" {{").unwrap();
    write_c_declarations(&mut output, definitions, CFamily::Cpp);
    writeln!(output, "}} // extern \"C\"").unwrap();
    output
}

fn write_c_declarations(output: &mut String, definitions: &[IntrinsicDefinition], family: CFamily) {
    for definition in definitions {
        writeln!(output, "/* {} */", definition.description).unwrap();
        let result = definition
            .result
            .map(|ty| c_type(ty, family))
            .unwrap_or("void");
        let parameters = if definition.parameters.is_empty() {
            "void".into()
        } else {
            definition
                .parameters
                .iter()
                .map(|parameter| c_parameter(parameter, family))
                .collect::<Vec<_>>()
                .join(", ")
        };
        writeln!(output, "{result} {}({parameters});", definition.symbol).unwrap();
        writeln!(output).unwrap();
    }
}

#[derive(Clone, Copy)]
enum CFamily {
    C,
    Cpp,
}

fn c_type(ty: AbiType, family: CFamily) -> &'static str {
    match (ty, family) {
        (AbiType::U8, CFamily::C) => "uint8_t",
        (AbiType::U8, CFamily::Cpp) => "uint8_t",
        (AbiType::ConstU8Pointer, CFamily::C) => "const uint8_t *",
        (AbiType::ConstU8Pointer, CFamily::Cpp) => "const uint8_t *",
        (AbiType::MutU8Pointer, CFamily::C) => "uint8_t *",
        (AbiType::MutU8Pointer, CFamily::Cpp) => "uint8_t *",
    }
}

fn c_parameter(parameter: &IntrinsicParameter, family: CFamily) -> String {
    let ty = c_type(parameter.ty, family);
    if ty.ends_with('*') {
        format!("{ty}{}", parameter.name)
    } else {
        format!("{ty} {}", parameter.name)
    }
}

fn render_rust(definitions: &[IntrinsicDefinition]) -> String {
    let mut output = String::new();
    writeln!(output, "// Generated by `waterbear wasm header`.").unwrap();
    writeln!(output).unwrap();
    writeln!(output, "unsafe extern \"C\" {{").unwrap();
    for definition in definitions {
        writeln!(output, "    /// {}", definition.description).unwrap();
        let parameters = definition
            .parameters
            .iter()
            .map(|parameter| format!("{}: {}", parameter.name, rust_type(parameter.ty)))
            .collect::<Vec<_>>()
            .join(", ");
        let result = definition
            .result
            .map(|ty| format!(" -> {}", rust_type(ty)))
            .unwrap_or_default();
        writeln!(
            output,
            "    pub fn {}({parameters}){result};",
            definition.symbol
        )
        .unwrap();
    }
    writeln!(output, "}}").unwrap();
    output
}

fn rust_type(ty: AbiType) -> &'static str {
    match ty {
        AbiType::U8 => "u8",
        AbiType::ConstU8Pointer => "*const u8",
        AbiType::MutU8Pointer => "*mut u8",
    }
}

#[cfg(test)]
mod tests {
    use super::{HeaderLanguage, render};

    #[test]
    fn renders_c_declarations() {
        let output = render(HeaderLanguage::C);
        assert!(output.contains("#include <stdint.h>"));
        assert!(output.contains("uint8_t waterbear_vmu_sfr_p7_read(void);"));
        assert!(output.contains(
            "void waterbear_vmu_xram_copy_from_main(uint8_t bank, uint8_t offset, const uint8_t *source, uint8_t length);"
        ));
    }

    #[test]
    fn renders_cpp_declarations_with_c_linkage() {
        let output = render(HeaderLanguage::Cpp);
        assert!(output.contains("#include <stdint.h>"));
        assert!(output.contains("extern \"C\" {"));
        assert!(output.contains("uint8_t waterbear_vmu_xram_read(uint8_t bank, uint8_t offset);"));
    }

    #[test]
    fn renders_rust_declarations() {
        let output = render(HeaderLanguage::Rust);
        assert!(output.contains("unsafe extern \"C\" {"));
        assert!(output.contains("pub fn waterbear_vmu_sfr_p7_read() -> u8;"));
        assert!(output.contains(
            "pub fn waterbear_vmu_xram_copy_to_main(destination: *mut u8, bank: u8, offset: u8, length: u8);"
        ));
    }
}
